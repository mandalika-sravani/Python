# Variable -- A container for a value (string, boolean, integer, float)
#               A variable behaves as if it was the value it contains

#Strings
first_name = "Veditha"
food = "tomato rice"
email = "testingemail341@gmail.com"

print(f"Hello {first_name}")
print(f"I like {food}")
print(f"This is my email: {email}")

#Integers
age = 25

print(f"Age is {age}")

#Float
gpa = 7.9

print(f"GPA is {gpa}")

#Boolean
isStudent = True

print(f"Is {first_name} a student : {isStudent}")
